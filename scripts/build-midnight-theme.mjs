// Builds the Midnight Ink theme sheets (loaded only while that theme is chosen).
//   src/styles/themes/midnight-ink.css        document layer
//   src/styles/themes/midnight-ink-tools.css  shadow-root layer for Crypto tools
// Each output = hand-written tokens/refinements (scripts/theme/*.src.css)
// with the generated colour-mapping layer inserted at `/* @midnight-map */`.
// `node scripts/build-midnight-theme.mjs --check` fails when outputs are stale.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildLayer, scopeDocument, scopeShadow } from './theme/midnight-map.mjs';

const root = resolve(import.meta.dirname, '..');
const read = path => readFile(resolve(root, path), 'utf8');

export async function documentSources() {
  const html = await read('index.html');
  const links = [...html.matchAll(/<link\b[^>]*>/g)].map(m => m[0])
    .filter(tag => /rel="stylesheet"/.test(tag) && !/data-ox-theme-css=/.test(tag))
    .map(tag => (/(?:data-ox-lazy-href|href)="(src\/[^"?]+)/.exec(tag) || [])[1]).filter(Boolean);
  return Promise.all(links.map(async path => ({ path, css: await read(path) })));
}
export const TOOL_SHEETS = ['src/styles/components/tools-rail.css', 'src/markets/crypto/patterns/patterns.css', 'src/markets/crypto/bubbles/bubbles.css', 'src/markets/crypto/analytics/flow.css', 'src/styles/components/ui-polish-tools.css'];

export async function buildMidnight() {
  const header = '/* GENERATED by scripts/build-midnight-theme.mjs from scripts/theme/*.src.css — edit the source and run `npm run build:tools`. */\n';
  const doc = buildLayer(await documentSources(), scopeDocument);
  const tools = buildLayer(await Promise.all(TOOL_SHEETS.map(async path => ({ path, css: await read(path) }))), scopeShadow);
  const fill = (src, layer) => header + src.replace('/* @midnight-map */', () => layer.css.trim());
  return {
    'src/styles/themes/midnight-ink.css': fill(await read('scripts/theme/midnight-ink.src.css'), doc),
    'src/styles/themes/midnight-ink-tools.css': fill(await read('scripts/theme/midnight-ink-tools.src.css'), tools),
    stats: { document: { rules: doc.rules, changed: doc.changed }, tools: { rules: tools.rules, changed: tools.changed } },
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { stats, ...files } = await buildMidnight();
  const check = process.argv.includes('--check');
  for (const [path, css] of Object.entries(files)) {
    if (check) {
      const current = await read(path).catch(() => '');
      if (current !== css) { console.error(`${path} is stale; run npm run build:tools`); process.exit(1); }
    } else await writeFile(resolve(root, path), css);
  }
  console.log(`Midnight Ink ${check ? 'verified' : 'built'}: ${stats.document.rules} document rules (${stats.document.changed} remapped), ${stats.tools.rules} tool rules (${stats.tools.changed} remapped), ${Object.values(files).map(f => (f.length / 1024).toFixed(1) + 'KB').join(' + ')}`);
}
